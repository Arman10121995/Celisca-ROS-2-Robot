"""Training templates for legged robots without a provisioned policy (R3.6/R12).

A template is an rl_sar policy directory without a checkpoint (base.yaml,
config.yaml, source.json): the joint order, standing pose, PD gains,
action scale and control period a fresh policy is trained and deployed
in. Each entry comes from a published open-source training configuration
for the same robot, cited in ``source``; nothing here is tuned for
results. ``write_template`` writes it, as bhl_training does for the
Berkeley Humanoid Lite.
"""
import hashlib
import json
import tempfile
from pathlib import Path

import yaml

# legged_gym (leggedrobotics/legged_gym, BSD-3-Clause) ANYmal C flat/rough
# configuration: default_joint_angles, control stiffness 80 N m/rad and
# damping 2 N m s/rad on every joint, action_scale 0.5, sim dt 0.005 s with
# decimation 4. Joint names match robot_assets' ANYmal URDF (asset_anymal);
# effort limits are that URDF's own (80 N m). Its flat config's reward
# weights (orientation -5, torques -2.5e-5, feet_air_time 2) replace the
# trainer's Go2-sized walk weights for this robot.
ANYMAL_POSE = {'LF_HAA': 0.0, 'LH_HAA': 0.0, 'RF_HAA': -0.0, 'RH_HAA': -0.0,
               'LF_HFE': 0.4, 'LH_HFE': -0.4, 'RF_HFE': 0.4, 'RH_HFE': -0.4,
               'LF_KFE': -0.8, 'LH_KFE': 0.8, 'RF_KFE': -0.8, 'RH_KFE': 0.8}

TEMPLATES = {
    'asset_anymal': dict(
        name='lab_anymal', robot='anymal',
        source='legged_gym anymal_c config (default_joint_angles, stiffness 80, damping 2, action_scale 0.5, '
               'dt 0.005, decimation 4); https://github.com/leggedrobotics/legged_gym',
        joints=['LF_HAA', 'LF_HFE', 'LF_KFE', 'RF_HAA', 'RF_HFE', 'RF_KFE',
                'LH_HAA', 'LH_HFE', 'LH_KFE', 'RH_HAA', 'RH_HFE', 'RH_KFE'],
        pose=ANYMAL_POSE, kp=80.0, kd=2.0, action_scale=0.5, effort=80.0, dt=0.005, decimation=4,
        # legged_gym AnymalCFlatCfg.rewards.scales over its LeggedRobotCfg defaults.
        walk_rewards=dict(orientation=-5.0, torques=-2.5e-5, feet_air_time=2.0)),
}


def write_template(profile, directory=None):
    """Write the training template of *profile*; returns its directory."""
    spec = TEMPLATES[profile]
    joints = list(spec['joints'])
    n = len(joints)
    digest = hashlib.sha256(json.dumps(spec, sort_keys=True).encode()).hexdigest()
    if directory is None:
        # The leaf is the template's name (recorded as template_policy on export).
        directory = Path(tempfile.gettempdir()) / ('robot_lab_template_%s' % digest[:12]) / spec['name']
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    pose = [float(spec['pose'][j]) for j in joints]
    gains = dict(kp=[float(spec['kp'])] * n, kd=[float(spec['kd'])] * n, effort=[float(spec['effort'])] * n)
    (directory / 'base.yaml').write_text(yaml.safe_dump({spec['robot']: dict(
        dt=spec['dt'], decimation=spec['decimation'], num_of_dofs=n, wheel_indices=[],
        fixed_kp=gains['kp'], fixed_kd=gains['kd'], torque_limits=gains['effort'],
        default_dof_pos=pose, joint_names=joints, joint_mapping=list(range(n)))}, sort_keys=False))
    (directory / 'config.yaml').write_text(yaml.safe_dump({spec['robot'] + '/' + spec['name']: dict(
        model_name='', num_observations=9 + 3 * n,
        observations=['ang_vel', 'gravity_vec', 'commands', 'dof_pos', 'dof_vel', 'actions'],
        observations_history=[], observations_history_priority='time', default_commands=[0.0, 0.0, 0.0],
        clip_obs=100.0, clip_actions_lower=[-100.0] * n, clip_actions_upper=[100.0] * n,
        rl_kp=gains['kp'], rl_kd=gains['kd'], num_of_dofs=n, action_scale=[float(spec['action_scale'])] * n,
        wheel_indices=[], lin_vel_scale=2.0, ang_vel_scale=0.25, dof_pos_scale=1.0, dof_vel_scale=0.05,
        commands_scale=[2.0, 2.0, 0.25], torque_limits=gains['effort'], default_dof_pos=pose,
        joint_mapping=list(range(n)), dt=spec['dt'], decimation=spec['decimation'])}, sort_keys=False))
    (directory / 'source.json').write_text(json.dumps(dict(
        robot=spec['robot'], variant=spec['name'], profile=profile, upstream=spec['source'],
        template_sha256=digest, note='training template generated by robot_lab_adapter.legged_templates; no policy'),
        indent=1) + '\n')
    return directory
