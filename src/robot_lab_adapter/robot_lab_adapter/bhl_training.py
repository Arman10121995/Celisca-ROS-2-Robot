"""Berkeley Humanoid Lite in the legged trainer (R5.3): contract template and export.

BHL deploys through ``humanoid_policy_controller`` (bhl_policy.py), not the
rl_sar ``legged-policy-controller``.  Its contract is the vendored upstream
``configs/policy_humanoid.yaml``: 22 joints (arms first), joint-position
actions ``default + 0.25 * action``, kp/kd 10/2 (arms) and 20/2 (legs),
effort limits 4/6 N m, one decision every 0.04 s, and the unscaled
observation ``command, gyro, gravity, q - default, dq, previous action``.

``write_template`` turns that config into an rl_sar-layout directory the
trainer loads like any provisioned template (all observation scales 1, PD
step 1/250 s: the deployed effort-command rate, so in-step PD matches the
controller's zero-order hold; decimation 10).  The trainer's student
observes ``ang_vel, gravity_vec, commands, ...``; ``export_bhl`` writes the
trained actor as an ONNX whose first layer is permuted to BHL's
commands-first order, beside an unchanged copy of the upstream config, so
``humanoid_policy_controller`` loads it with ``policy_dir:=<dir>``.
"""
from __future__ import annotations

import hashlib
import json
import tempfile
from pathlib import Path

import yaml

from .bhl_balance import BALANCE_RATE_HZ
from .bhl_policy import COMMAND_WIDTH, load_policy_config, upstream_dir

PROFILE = 'berkeley_humanoid_lite_sim'
POLICY_NAME = 'policy_humanoid'
TEMPLATE_NAME = 'bhl_policy_humanoid'
EFFORT_DT = 1.0 / BALANCE_RATE_HZ


def _upstream_config(name=POLICY_NAME):
    return yaml.safe_load((upstream_dir() / 'configs' / ('%s.yaml' % name)).read_text())


def write_template(directory=None, name=POLICY_NAME):
    """rl_sar template (base.yaml, config.yaml, source.json) of the upstream BHL contract."""
    config = load_policy_config(name=name)
    if list(config.action_indices) != list(range(len(config.joints))):
        raise ValueError('%s does not act on every joint; the trainer drives all contract joints' % name)
    decimation = int(round(config.policy_dt / EFFORT_DT))
    if abs(decimation * EFFORT_DT - config.policy_dt) > 1e-9:
        raise ValueError('policy period %.4f s is not a whole number of effort steps' % config.policy_dt)
    raw = (upstream_dir() / 'configs' / ('%s.yaml' % name)).read_bytes()
    if directory is None:
        # The leaf is the template's name (recorded as template_policy on export).
        directory = (Path(tempfile.gettempdir()) / ('robot_lab_bhl_%s' % hashlib.sha256(raw).hexdigest()[:12])
                     / TEMPLATE_NAME)
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    n = len(config.joints)
    vec = lambda values: [float(v) for v in values]  # noqa: E731
    (directory / 'base.yaml').write_text(yaml.safe_dump({'bhl': dict(
        dt=EFFORT_DT, decimation=decimation, num_of_dofs=n, wheel_indices=[],
        fixed_kp=vec(config.kp), fixed_kd=vec(config.kd), torque_limits=vec(config.effort_limits),
        default_dof_pos=vec(config.nominal), joint_names=list(config.joints),
        joint_mapping=list(range(n)))}, sort_keys=False))
    (directory / 'config.yaml').write_text(yaml.safe_dump({'bhl/' + name: dict(
        model_name='', num_observations=config.num_observations,
        observations=['commands', 'ang_vel', 'gravity_vec', 'dof_pos', 'dof_vel', 'actions'],
        observations_history=[], observations_history_priority='time', default_commands=[0.0, 0.0, 0.0],
        clip_obs=1e4, clip_actions_lower=[config.action_limit_lower] * n,
        clip_actions_upper=[config.action_limit_upper] * n, rl_kp=vec(config.kp), rl_kd=vec(config.kd),
        num_of_dofs=n, action_scale=[config.action_scale] * n, wheel_indices=[], lin_vel_scale=1.0,
        ang_vel_scale=1.0, dof_pos_scale=1.0, dof_vel_scale=1.0, commands_scale=[1.0, 1.0, 1.0],
        torque_limits=vec(config.effort_limits), default_dof_pos=vec(config.nominal),
        joint_mapping=list(range(n)), dt=EFFORT_DT, decimation=decimation)}, sort_keys=False))
    (directory / 'source.json').write_text(json.dumps(dict(
        robot='bhl', variant=name, profile=PROFILE,
        upstream='robot_lab_robots/_upstream/Berkeley-Humanoid-Lite/configs/%s.yaml' % name,
        config_sha256=hashlib.sha256(raw).hexdigest(),
        note='training template generated by robot_lab_adapter.bhl_training; no policy'), indent=1) + '\n')
    return directory


def input_permutation(num_dofs):
    """For each trainer input index, its index in BHL's commands-first observation."""
    trainer = ['ang_vel', 'gravity', 'commands']
    bhl = ['commands', 'ang_vel', 'gravity']
    blocks = {name: COMMAND_WIDTH * bhl.index(name) for name in trainer}
    head = [blocks[name] + k for name in trainer for k in range(COMMAND_WIDTH)]
    return head + list(range(3 * COMMAND_WIDTH, 3 * COMMAND_WIDTH + 3 * num_dofs))


def export_bhl(model, out_dir, run, name=POLICY_NAME):
    """``configs/<name>.yaml`` (upstream, unchanged) + ``checkpoints/<name>.onnx`` (BHL input order)."""
    from .ppo import export_onnx
    config = _upstream_config(name)
    out = Path(out_dir)
    (out / 'configs').mkdir(parents=True, exist_ok=True)
    (out / 'checkpoints').mkdir(parents=True, exist_ok=True)
    checkpoint = out / config['policy_checkpoint_path']
    if checkpoint.parent != out / 'checkpoints':
        raise ValueError('unexpected upstream checkpoint path %s' % config['policy_checkpoint_path'])
    export_onnx(model, str(checkpoint), input_permutation=input_permutation(len(config['joints'])))
    (out / 'configs' / ('%s.yaml' % name)).write_bytes(
        (upstream_dir() / 'configs' / ('%s.yaml' % name)).read_bytes())
    (out / 'source.json').write_text(json.dumps(dict(
        profile=PROFILE, policy_name=name, trained_by='robot_lab_adapter.legged_train',
        task=run.get('task'), run=run.get('name'), revision=run.get('revision', ''),
        onnx_sha256=hashlib.sha256(checkpoint.read_bytes()).hexdigest(),
        observation_order='command, gyro, gravity, q - default, dq, previous action (bhl_policy.build_observation)',
        qualification='trained in the MuJoCo training environment; runtime evidence pending'), indent=1) + '\n')
    load_policy_config(upstream=out, name=name)    # must load like the vendored checkpoints
    return out
