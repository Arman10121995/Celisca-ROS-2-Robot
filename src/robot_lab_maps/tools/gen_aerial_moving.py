#!/usr/bin/env python3
"""R5.11 - aerial test field with people walking across the drone corridor.

``aerial_moving``: a flat 30 x 30 m field, four static pillars, and two
walking actors (the lab's walking mesh, 1.77 m tall) pacing back and forth
across the x axis at x = 0 and x = 5 m. A drone flying from (-10, 0) to
(10, 0) at 1.2 m crosses both paths, so moving-obstacle prediction,
holding and replanning can be exercised. The occupancy map holds the static
pillars only (actors move). Regenerating writes byte-identical files.

    python3 tools/gen_aerial_moving.py [--check]
"""
import argparse
from pathlib import Path

NAME = 'aerial_moving'
SIZE = 30.
RESOLUTION = .1
PILLARS = ((-6., 8.), (6., -8.), (12., 10.), (-12., -10.))     # x, y; 1 x 1 x 4 m
SKIN = 'package://robot_lab_description/meshes/MaleVisitorWalkDownloaded.dae'
WALKERS = ((0., -6., 6., 6.), (5., 6., -6., 7.5))              # x, y from, y to, seconds per leg


def walker(index, x, y0, y1, leg):
    import math
    yaw = math.pi / 2 if y1 > y0 else -math.pi / 2
    points = [(0., y0, yaw), (leg, y1, yaw), (leg + 1., y1, yaw + math.pi), (2 * leg + 1., y0, yaw + math.pi),
              (2 * leg + 2., y0, yaw)]
    waypoints = ''.join('          <waypoint><time>%.2f</time><pose>%.2f %.2f 0 0 0 %.4f</pose></waypoint>\n'
                        % (t, x, y, a) for t, y, a in points)
    return ('    <actor name="walker_%d">\n      <skin><filename>%s</filename><scale>1</scale></skin>\n'
            '      <animation name="walk"><filename>%s</filename><interpolate_x>false</interpolate_x></animation>\n'
            '      <script>\n        <loop>true</loop>\n        <auto_start>true</auto_start>\n'
            '        <trajectory id="0" type="walk" tension="0">\n%s        </trajectory>\n      </script>\n'
            '    </actor>\n' % (index, SKIN, SKIN, waypoints))


def world():
    pillars = ''.join(
        '    <model name="pillar_%d">\n      <static>true</static>\n      <pose>%.1f %.1f 2 0 0 0</pose>\n'
        '      <link name="link">\n        <collision name="collision"><geometry><box><size>1 1 4</size></box>'
        '</geometry></collision>\n        <visual name="visual"><geometry><box><size>1 1 4</size></box></geometry>'
        '</visual>\n      </link>\n    </model>\n' % (i, x, y) for i, (x, y) in enumerate(PILLARS))
    walkers = ''.join(walker(i, *w) for i, w in enumerate(WALKERS))
    return ('<?xml version="1.0"?>\n<!-- Generated by tools/gen_aerial_moving.py - do not edit by hand. -->\n'
            '<sdf version="1.7">\n  <world name="%s">\n    <physics type="ode">\n'
            '      <max_step_size>0.004</max_step_size>\n    </physics>\n'
            '    <light name="sun" type="directional">\n      <cast_shadows>true</cast_shadows>\n'
            '      <pose>0 0 20 0 0 0</pose>\n      <diffuse>0.8 0.8 0.8 1</diffuse>\n'
            '      <direction>-0.5 0.3 -1.0</direction>\n    </light>\n'
            '    <model name="ground_plane">\n      <static>true</static>\n      <pose>0 0 -0.05 0 0 0</pose>\n'
            '      <link name="link">\n        <collision name="collision"><geometry><box><size>%g %g 0.1</size>'
            '</box></geometry></collision>\n        <visual name="visual"><geometry><box><size>%g %g 0.1</size>'
            '</box></geometry></visual>\n      </link>\n    </model>\n%s%s  </world>\n</sdf>\n'
            % (NAME, SIZE, SIZE, SIZE, SIZE, pillars, walkers))


def occupancy():
    cells = int(round(SIZE / RESOLUTION))
    grid = bytearray([254]) * (cells * cells)
    for x, y in PILLARS:
        for row in range(cells):
            cy = SIZE / 2 - (row + .5) * RESOLUTION
            if abs(cy - y) > .5:
                continue
            for column in range(cells):
                if abs((column + .5) * RESOLUTION - SIZE / 2 - x) <= .5:
                    grid[row * cells + column] = 0
    pgm = b'P5\n%d %d\n255\n' % (cells, cells) + bytes(grid)
    yaml = ('image: map.pgm\nmode: trinary\nresolution: %.3f\norigin: [%.3f, %.3f, 0.000000]\nnegate: 0\n'
            'occupied_thresh: 0.65\nfree_thresh: 0.196\n' % (RESOLUTION, -SIZE / 2, -SIZE / 2))
    return pgm, yaml.encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out-dir', default=str(Path(__file__).resolve().parent.parent / 'maps'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(args.out_dir) / NAME
    pgm, yaml = occupancy()
    files = {root / 'worlds' / (NAME + '.world'): world().encode(), root / 'maps' / 'map.pgm': pgm,
             root / 'maps' / 'map.yaml': yaml}
    if args.check:
        stale = [str(p) for p, data in files.items() if not p.is_file() or p.read_bytes() != data]
        print('Out of date: %s' % stale if stale else 'aerial_moving is up to date.')
        return 1 if stale else 0
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print('%s written' % root)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
