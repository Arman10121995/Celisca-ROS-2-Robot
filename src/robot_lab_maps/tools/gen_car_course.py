#!/usr/bin/env python3
"""Generate the car course: a cone slalom and a parking bay (R5.5).

The cars' remaining missions are a slalom and parking with curvature and
swept-footprint checks, and a final heading.  The course sits around the
nav_empty spawn (-0.5, -0.5, heading +x) inside a walled 12 x 6.5 m yard:

* five cones (r 0.1 m) on the line y = -0.5 at x = 1.0 ... 7.0, 1.5 m apart;
* slalom gates midway between cones, alternately 0.5 m left and right,
  heading +x: a 1.0 m swing every 1.5 m, which a 0.5 m turning radius
  can drive;
* a parking bay at the far end: two parked boxes 0.8 m apart with a back
  wall, open toward -y; the goal is the bay centre, heading +y (nose in).

Writes maps/car_course/worlds/car_course.world, maps/car_course/maps/
map.{pgm,yaml} (0.05 m, rasterised from the same primitives),
maps/car_course/course.json (cones, boxes, goals, for the mission's
footprint checks) and mjcf/car_course.xml.  Launch with map_name:=nav_empty
world_name:=car_course world_path:=<world> map_yaml:=<map.yaml>
(scripts/sim_car_course.sh).
"""
import json
import math
import os
import sys

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
_MAPS = os.path.dirname(_HERE)
CONE_RADIUS, CONE_HEIGHT = 0.1, 0.4
LINE_Y = -0.5
CONES = [(1.0 + 1.5 * i, LINE_Y) for i in range(5)]
YARD = (-2.5, -3.5, 10.5, 3.0)            # x0, y0, x1, y1 of the walls' inner faces
WALL = 0.1
BAY_X, BAY_Y = 8.9, 1.1                   # bay centre
BAY_GAP, BAY_DEPTH = 0.8, 0.9


def boxes():
    """(name, centre x, y, z, size x, y, z) of every box."""
    x0, y0, x1, y1 = YARD
    h = 0.5
    result = [("wall_south", (x0 + x1) / 2, y0 - WALL / 2, h / 2, x1 - x0 + 2 * WALL, WALL, h),
              ("wall_north", (x0 + x1) / 2, y1 + WALL / 2, h / 2, x1 - x0 + 2 * WALL, WALL, h),
              ("wall_west", x0 - WALL / 2, (y0 + y1) / 2, h / 2, WALL, y1 - y0, h),
              ("wall_east", x1 + WALL / 2, (y0 + y1) / 2, h / 2, WALL, y1 - y0, h)]
    # Parked boxes either side of the bay, and its back wall.
    for side, sign in (("left", -1), ("right", 1)):
        result.append(("parked_%s" % side, BAY_X + sign * (BAY_GAP / 2 + 0.2), BAY_Y, 0.15, 0.4, BAY_DEPTH, 0.3))
    result.append(("bay_back", BAY_X, BAY_Y + BAY_DEPTH / 2 + 0.05, 0.15, BAY_GAP + 0.8, 0.1, 0.3))
    return result


def goals():
    """Slalom gates then the bay: (x, y, yaw)."""
    gates = []
    for i in range(len(CONES) - 1):
        x = (CONES[i][0] + CONES[i + 1][0]) / 2
        y = LINE_Y + (0.5 if i % 2 == 0 else -0.5)
        gates.append((x, y, 0.0))
    return gates, (BAY_X, BAY_Y - 0.1, math.pi / 2)


def world():
    models = []
    for i, (x, y) in enumerate(CONES):
        models.append(f"""    <model name="cone_{i}">
      <static>true</static>
      <pose>{x} {y} {CONE_HEIGHT / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><cylinder><radius>{CONE_RADIUS}</radius><length>{CONE_HEIGHT}</length></cylinder></geometry></collision>
        <visual name="visual"><geometry><cylinder><radius>{CONE_RADIUS}</radius><length>{CONE_HEIGHT}</length></cylinder></geometry>
          <material><ambient>1 0.45 0.05 1</ambient><diffuse>1 0.45 0.05 1</diffuse></material></visual>
      </link>
    </model>""")
    for name, x, y, z, sx, sy, sz in boxes():
        models.append(f"""    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>0.45 0.47 0.5 1</ambient><diffuse>0.45 0.47 0.5 1</diffuse></material></visual>
      </link>
    </model>""")
    body = "\n".join(models)
    return f"""<?xml version="1.0" ?>
<!-- Generated by robot_lab_maps/tools/gen_car_course.py - do not edit by hand.
     Cone slalom and parking bay around the nav_empty spawn (R5.5). -->
<sdf version="1.7">
  <world name="car_course">
    <physics type="ode"><max_step_size>0.002</max_step_size></physics>
    <scene><ambient>0.5 0.5 0.5 1</ambient><background>0.7 0.7 0.7 1</background></scene>
    <light name="sun" type="directional">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.3 -1.0</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <material><ambient>0.6 0.6 0.6 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material></visual>
      </link>
    </model>
{body}
  </world>
</sdf>
"""


def occupancy(resolution=0.05):
    x0, y0, x1, y1 = YARD
    margin = 0.5
    ox, oy = x0 - margin, y0 - margin
    width = int(round((x1 - x0 + 2 * margin) / resolution))
    height = int(round((y1 - y0 + 2 * margin) / resolution))
    xs = ox + (np.arange(width) + 0.5) * resolution
    ys = oy + (np.arange(height) + 0.5) * resolution
    gx, gy = np.meshgrid(xs, ys)
    occupied = np.zeros_like(gx, dtype=bool)
    for _, x, y, _, sx, sy, _ in boxes():
        occupied |= (np.abs(gx - x) <= sx / 2) & (np.abs(gy - y) <= sy / 2)
    for x, y in CONES:
        occupied |= np.hypot(gx - x, gy - y) <= CONE_RADIUS
    outside = (gx < x0 - WALL) | (gx > x1 + WALL) | (gy < y0 - WALL) | (gy > y1 + WALL)
    image = np.where(occupied, 0, 254).astype(np.uint8)
    image[outside] = 205
    return np.flipud(image), (ox, oy), resolution


def main():
    root = os.path.join(_MAPS, "maps", "car_course")
    os.makedirs(os.path.join(root, "worlds"), exist_ok=True)
    os.makedirs(os.path.join(root, "maps"), exist_ok=True)
    world_path = os.path.join(root, "worlds", "car_course.world")
    with open(world_path, "w") as handle:
        handle.write(world())
    image, (ox, oy), resolution = occupancy()
    with open(os.path.join(root, "maps", "map.pgm"), "wb") as handle:
        handle.write(b"P5\n%d %d\n255\n" % (image.shape[1], image.shape[0]))
        handle.write(image.tobytes())
    with open(os.path.join(root, "maps", "map.yaml"), "w") as handle:
        handle.write("image: map.pgm\nmode: trinary\nresolution: %.3f\norigin: [%.3f, %.3f, 0.0]\n"
                     "negate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.196\n" % (resolution, ox, oy))
    gates, bay = goals()
    with open(os.path.join(root, "course.json"), "w") as handle:
        json.dump({"cones": [{"x": x, "y": y, "radius": CONE_RADIUS} for x, y in CONES],
                   "boxes": [{"name": n, "x": x, "y": y, "size": [sx, sy]} for n, x, y, _, sx, sy, _ in boxes()],
                   "slalom_goals": [{"x": x, "y": y, "yaw": yaw} for x, y, yaw in gates],
                   "parking_goal": {"x": bay[0], "y": bay[1], "yaw": bay[2]},
                   "bay": {"x": BAY_X, "y": BAY_Y, "gap_m": BAY_GAP, "depth_m": BAY_DEPTH}}, handle, indent=1)
    sys.path.insert(0, _HERE)
    import gen_mjcf_worlds
    mjcf, skipped = gen_mjcf_worlds.convert_world(world_path, "car_course")
    with open(os.path.join(_MAPS, "mjcf", "car_course.xml"), "w") as handle:
        handle.write(mjcf)
    print("car_course: %d cones, %d boxes, map %dx%d, mjcf %d geoms%s" % (
        len(CONES), len(boxes()), image.shape[1], image.shape[0], mjcf.count("<geom"),
        (" skipped: %s" % skipped) if skipped else ""))


if __name__ == "__main__":
    main()
