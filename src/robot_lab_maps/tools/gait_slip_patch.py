#!/usr/bin/env python3
"""Author ``gait_slip_patch``: the low-relief gait world with a slippery plate (R10.6).

The bounded slip/support-loss recovery in ``gait_recovery.py`` was unit-tested
only. This world gives it a physical cause: ``gait_low_relief`` (same 4 m,
8 mm heightfield, spawn and map) with a 4 mm, 0.8 x 1.0 m plate of friction
0.05 starting 0.35 m ahead of the spawn, in the gait's straight walking
path. It lies 8–12 mm up, just above the relief peaks, so feet on it touch
only the plate. Measured 2026-11-19: the octopod crosses it at up to its
0.045 m/s limit without a measured slip (slow walking asks little
friction), and plates rolled 4-6° far enough to out-pull the friction
exceed the gait's 2 cm terrain envelope, so the gait stops before them. Friction 0.05 is about ice on steel; the heightfield
keeps its 0.9. The MJCF is the checked-in ``gait_low_relief.xml`` (same
staged heightfield asset) plus the plate: the standard converter does not
carry this plate's friction. MuJoCo uses the larger friction of two geoms
unless one has a higher ``priority``. The MuJoCo spawner gives robot geoms
with authored friction priority 1, so the plate has priority 2: without it
the feet's own friction applied and μ 0.05 and 0.01 walked identically.
"""
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET

import math
# Flat (roll 0). Rolled 4-6 deg plates, which would out-pull friction 0.05,
# exceed the gait's 2 cm terrain envelope (measured 2026-11-19).
PLATE = dict(name='slip_plate', pose=(0., 0., .010), size=(.8, 1., .004), mu=.05, roll=0.)


def generate(root=None):
    root = Path(root or Path(__file__).resolve().parents[1])
    source, target = root/'maps/gait_low_relief', root/'maps/gait_slip_patch'
    for sub in ('worlds', 'maps'):
        (target/sub).mkdir(parents=True, exist_ok=True)
    for name in ('terrain.png', 'terrain_visual.obj'):
        shutil.copyfile(source/'worlds'/name, target/'worlds'/name)
    for name in ('map.pgm', 'map.yaml'):
        shutil.copyfile(source/'maps'/name, target/'maps'/name)
    tree = ET.parse(source/'worlds/gait_low_relief.world')
    world = tree.getroot().find('world')
    world.set('name', 'gait_slip_patch')
    model = ET.SubElement(world, 'model', name=PLATE['name'])
    ET.SubElement(model, 'static').text = 'true'
    ET.SubElement(model, 'pose').text = '%g %g %g %g 0 0' % (*PLATE['pose'], PLATE['roll'])
    link = ET.SubElement(model, 'link', name='link')
    for tag in ('collision', 'visual'):
        element = ET.SubElement(link, tag, name=tag)
        ET.SubElement(ET.SubElement(ET.SubElement(element, 'geometry'), 'box'), 'size').text = '%g %g %g' % PLATE['size']
        if tag == 'collision':
            ode = ET.SubElement(ET.SubElement(ET.SubElement(element, 'surface'), 'friction'), 'ode')
            ET.SubElement(ode, 'mu').text = str(PLATE['mu'])
            ET.SubElement(ode, 'mu2').text = str(PLATE['mu'])
        else:
            material = ET.SubElement(element, 'material')
            ET.SubElement(material, 'ambient').text = '.7 .85 .95 1'
            ET.SubElement(material, 'diffuse').text = '.7 .85 .95 1'
    ET.indent(tree, space='  ')
    tree.write(target/'worlds/gait_slip_patch.world', encoding='utf-8', xml_declaration=True)
    mjcf = (root/'mjcf/gait_low_relief.xml').read_text()
    header = mjcf[:mjcf.index('-->')+3]
    mjcf = mjcf.replace(header, '<!-- Generated by robot_lab_maps/tools/gait_slip_patch.py from mjcf/gait_low_relief.xml\n'
                        '     plus slip_plate - do not edit by hand. -->')
    mjcf = mjcf.replace('<mujoco model="gait_low_relief">', '<mujoco model="gait_slip_patch">')
    plate = ('    <geom name="%s" pos="%g %g %g" quat="%.6f %.6f 0 0" type="box" size="%g %g %g" friction="%g 0.005 0.0001" '
             'priority="2" rgba="0.7 0.85 0.95 1" />\n' % (PLATE['name'], *PLATE['pose'], math.cos(PLATE['roll']/2),
             math.sin(PLATE['roll']/2), *(v/2 for v in PLATE['size']), PLATE['mu']))
    marker = '    <light '
    mjcf = mjcf.replace(marker, plate+marker, 1)
    (root/'mjcf/gait_slip_patch.xml').write_text(mjcf)


if __name__ == '__main__':
    generate()
